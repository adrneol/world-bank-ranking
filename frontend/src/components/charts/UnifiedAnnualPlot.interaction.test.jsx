import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { afterEach, expect, it, vi } from 'vitest';
import UnifiedAnnualPlot from './UnifiedAnnualPlot.jsx';

let cleanup;
afterEach(() => { cleanup?.(); vi.restoreAllMocks(); });
it('inspects a partly visible year whose centre is outside the scrolled viewport', () => {
  vi.spyOn(HTMLElement.prototype, 'clientWidth', 'get').mockReturnValue(100);
  vi.spyOn(window, 'requestAnimationFrame').mockImplementation(callback => { callback(); return 1; });
  const container = document.createElement('div');
  document.body.appendChild(container);
  const root = createRoot(container);
  const years = Array.from({ length: 20 }, (_, index) => 2000 + index);
  act(() => root.render(<UnifiedAnnualPlot years={years} regions={[{ id: 'level', unit: 'current US$',
    series: [{ id: 'a', label: 'Japan', values: years.map(() => 10) }] }]} />));
  cleanup = () => { act(() => root.unmount()); container.remove(); };
  const scroller = container.querySelector('.annual-plot-scroll');
  const strip = container.querySelector('.annual-plot-strip');
  vi.spyOn(strip, 'getBoundingClientRect').mockReturnValue({ left: -16 });
  scroller.scrollLeft = 16;
  act(() => scroller.dispatchEvent(new Event('scroll', { bubbles: true })));
  act(() => strip.dispatchEvent(new MouseEvent('click', { clientX: 1, bubbles: true })));
  expect(container.querySelector('.annual-tooltip')?.textContent).toContain('2000');
});
it('dismisses inspected values by Close, outside pointer, Escape and changed chart state', () => {
  vi.spyOn(HTMLElement.prototype, 'clientWidth', 'get').mockReturnValue(400);
  const container = document.createElement('div');
  document.body.appendChild(container);
  const root = createRoot(container);
  const regions = [{ id: 'levels', unit: 'current US$', series: [{ id: 'gdp', label: 'GDP', color: '#123456', values: [10, 20] }] }];
  const render = type => act(() => root.render(<UnifiedAnnualPlot years={[2020, 2021]} regions={regions} type={type} />));
  cleanup = () => { act(() => root.unmount()); container.remove(); };
  render('line');
  const plot = container.querySelector('[aria-label="Annual observations"]');
  const strip = container.querySelector('.annual-plot-strip');
  const pointer = (type, pointerType = 'mouse') => {
    const event = new MouseEvent(type, { clientX: 20, bubbles: true, relatedTarget: document.body });
    Object.defineProperty(event, 'pointerType', { value: pointerType });
    act(() => strip.dispatchEvent(event));
  };
  pointer('pointermove');
  expect(container.querySelector('.annual-tooltip').dataset.pinned).toBe('false');
  pointer('pointerout');
  expect(container.querySelector('.annual-tooltip')).toBeNull();
  pointer('click', 'touch');
  expect(container.querySelector('.annual-tooltip').dataset.pinned).toBe('true');
  pointer('pointerout');
  expect(container.querySelector('.annual-tooltip')).not.toBeNull();
  act(() => container.querySelector('[aria-label="Close chart values"]').click());
  const inspect = () => act(() => plot.dispatchEvent(new KeyboardEvent('keydown', { key: 'Home', bubbles: true })));
  inspect();
  expect(container.querySelector('.annual-tooltip').textContent).toContain('2020');
  act(() => container.querySelector('[aria-label="Close chart values"]').click());
  expect(container.querySelector('.annual-tooltip')).toBeNull();
  inspect();
  act(() => document.body.dispatchEvent(new Event('pointerdown', { bubbles: true })));
  expect(container.querySelector('.annual-tooltip')).toBeNull();
  inspect();
  act(() => plot.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true })));
  expect(container.querySelector('.annual-tooltip')).toBeNull();
  inspect();
  render('bar');
  expect(container.querySelector('.annual-tooltip')).toBeNull();
  inspect();
  regions[0].series[0].values = [30, 40];
  render('bar');
  expect(container.querySelector('.annual-tooltip')).toBeNull();
});
